// Reactive client-side internationalization (i18n) engine for BYOS Webmail
import { createSignal } from "solid-js";

function getInitialLocale(): string {
  if (typeof window !== "undefined") {
    const stored = localStorage.getItem("byos_language");
    if (stored) return stored.toLowerCase().split("-")[0];
    if (document.documentElement.lang) {
      return document.documentElement.lang.toLowerCase().split("-")[0];
    }
  }
  return "en";
}

const [currentLocale, setCurrentLocaleSignal] = createSignal<string>(getInitialLocale());

export const locale = currentLocale;

export function setLocale(lang: string) {
  if (!lang) return;
  const clean = lang.toLowerCase().split("-")[0];
  setCurrentLocaleSignal(clean);
  if (typeof window !== "undefined") {
    localStorage.setItem("byos_language", clean);
    document.documentElement.lang = clean;
  }
}

