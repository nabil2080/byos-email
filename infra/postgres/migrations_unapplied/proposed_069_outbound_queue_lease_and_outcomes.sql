-- Context:
--   Remediates concurrency and reliability defects in services/outbound-worker:
--   1. Adds lease ownership columns (lease_token, lease_owner, claimed_at,
--      lease_expires_at, smtp_phase, last_smtp_code, last_error) to
--      outbound_queue so multi-worker claiming executes atomically in a SQL
--      transaction and stale workers are fenced from mutating newer attempts.
--   2. Extends outbound_queue.status to include 'processing' (active worker
--      lease) and 'outcome_unknown' (loss/crash after entering
--      'terminator_in_flight' where auto-retry could cause duplicate delivery).
--   3. Enforces explicit SMTP transaction phase tracking
--      ('claimed', 'pre_data', 'data_streaming', 'terminator_in_flight',
--      'accepted_by_mta') in outbound_queue_smtp_phase_check so pre-terminator
--      DATA aborts remain safely retryable while post-terminator ambiguity
--      quarantines to 'outcome_unknown'.
--   4. Adds lease_token / smtp_phase telemetry and partial unique indexes to
--      delivery_log to guarantee at most one settled terminal entry per
--      delivery_id and idempotent per-attempt logging without weakening
--      outbound_worker least-privilege RBAC.
--
-- Ordering note:
--   Release A.2 precedes Release B2 deployment. If Release B1's proposed
--   migration (docs/attachment_delivery_schema_migration_proposal.md) is
--   promoted to infra/postgres/init/, it should follow this migration
