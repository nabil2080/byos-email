-- 1. Extend outbound_queue for lease fencing, SMTP phase checkpointing, and outcome_unknown
ALTER TABLE outbound_queue
    ADD COLUMN IF NOT EXISTS lease_token      uuid,
    ADD COLUMN IF NOT EXISTS lease_owner      text,
    ADD COLUMN IF NOT EXISTS claimed_at       timestamptz,
    ADD COLUMN IF NOT EXISTS lease_expires_at timestamptz,
    ADD COLUMN IF NOT EXISTS smtp_phase       text,
    ADD COLUMN IF NOT EXISTS last_smtp_code   integer,
    ADD COLUMN IF NOT EXISTS last_error       text;

-- Replace the inline status CHECK constraint safely (works regardless of autogenerated constraint name)
DO $$
DECLARE
    c_name text;
BEGIN
    FOR c_name IN
        SELECT con.conname
        FROM pg_constraint con
        JOIN pg_class rel ON rel.oid = con.conrelid
        JOIN pg_namespace nsp ON nsp.oid = rel.relnamespace
        WHERE nsp.nspname = 'public'
          AND rel.relname = 'outbound_queue'
          AND con.contype = 'c'
          AND pg_get_constraintdef(con.oid) ILIKE '%status%'
    LOOP
        EXECUTE format('ALTER TABLE public.outbound_queue DROP CONSTRAINT IF EXISTS %I', c_name);
    END LOOP;

    ALTER TABLE public.outbound_queue
        ADD CONSTRAINT outbound_queue_status_check
        CHECK (status IN (
            'pending',
            'processing',
            'accepted_by_mta',
            'delivered',
            'bounced',
            'expired',
            'outcome_unknown'
        ));
END $$;

DO $$
BEGIN
    -- Normalize any row from an earlier Release A.2 draft safely before replacing check constraint.
    UPDATE public.outbound_queue
    SET smtp_phase = 'terminator_in_flight'
    WHERE smtp_phase = 'data_in_flight';

    ALTER TABLE public.outbound_queue
        DROP CONSTRAINT IF EXISTS outbound_queue_smtp_phase_check;

    ALTER TABLE public.outbound_queue
        ADD CONSTRAINT outbound_queue_smtp_phase_check
        CHECK (smtp_phase IS NULL OR smtp_phase IN (
            'claimed',
            'pre_data',
            'data_streaming',
            'terminator_in_flight',
            'accepted_by_mta'
        ));

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'outbound_queue_processing_lease_check'
    ) THEN
        ALTER TABLE public.outbound_queue
            ADD CONSTRAINT outbound_queue_processing_lease_check
            CHECK (
                (status = 'processing' AND lease_token IS NOT NULL AND lease_expires_at IS NOT NULL)
                OR
                (status <> 'processing' AND lease_token IS NULL AND lease_expires_at IS NULL)
            );
    END IF;
END $$;

-- Fast claim, lease-reclaim, expiration-reaper, and manual-reconciliation indexes
CREATE INDEX IF NOT EXISTS idx_outbound_queue_claimable
    ON outbound_queue (next_attempt_at ASC)
    WHERE status = 'pending';

CREATE INDEX IF NOT EXISTS idx_outbound_queue_processing_lease
    ON outbound_queue (lease_expires_at ASC)
    WHERE status = 'processing';

CREATE INDEX IF NOT EXISTS idx_outbound_queue_pending_expiry
    ON outbound_queue (expires_at ASC)
    WHERE status = 'pending';

CREATE INDEX IF NOT EXISTS idx_outbound_queue_outcome_unknown
    ON outbound_queue (failed_at DESC)
    WHERE status = 'outcome_unknown';

-- 2. Extend delivery_log for attempt-level observability and terminal deduplication
ALTER TABLE delivery_log
    ADD COLUMN IF NOT EXISTS lease_token uuid,
    ADD COLUMN IF NOT EXISTS smtp_phase  text;

-- Guarantee at most one settled terminal log row ('delivered', 'bounced', or 'expired') per outbound delivery
CREATE UNIQUE INDEX IF NOT EXISTS idx_delivery_log_outbound_settled_unique
    ON delivery_log (delivery_id)
    WHERE direction = 'outbound' AND status IN ('delivered', 'bounced', 'expired');

-- Guarantee at most one 'outcome_unknown' audit row per outbound delivery
CREATE UNIQUE INDEX IF NOT EXISTS idx_delivery_log_outbound_unknown_unique
    ON delivery_log (delivery_id)
    WHERE direction = 'outbound' AND status = 'outcome_unknown';

-- Guarantee at most one delivery_log entry per (delivery_id, lease_token, status) for fenced retries/outcomes
CREATE UNIQUE INDEX IF NOT EXISTS idx_delivery_log_outbound_attempt_unique
    ON delivery_log (delivery_id, lease_token, status)
    WHERE direction = 'outbound' AND lease_token IS NOT NULL;

-- 3. Least-privilege defense-in-depth preservation (same narrow grants as 002/003/007)
DO $$
DECLARE
    tbl text;
BEGIN
    FOREACH tbl IN ARRAY ARRAY[
        'public.root_secrets',
        'public.message_metadata',
        'public.device_mailbox_access',
        'public.org_recovery_principals',
        'public.storage_connections'
    ]
    LOOP
        IF to_regclass(tbl) IS NOT NULL THEN
            EXECUTE format('REVOKE ALL ON TABLE %s FROM outbound_worker', tbl);
        END IF;
    END LOOP;
END $$;
